"""티메토 로우폴리 아틀라스 텍스처 (128x128, nearest 전제).

레이아웃 (px, 좌상단 원점):
  (0,0)-(64,64)    얼굴 정면 (앞머리 + 눈 + 입 + 홍조)
  (64,0)-(128,64)  머리 측/후면 (라벤더 + 음영)
  (0,64)-(64,96)   상체 정면 (가운 + 남색 이너 + 노란 리본)
  (64,64)-(96,96)  상체 측/후면 (가운 흰색 + 이음선)
  (96,64)-(128,96) 팔/소매
  (0,96)-(32,128)  다리/스타킹
  (32,96)-(64,128) 부츠
  (64,96)-(96,128) 라벤더 단색 (머리 파츠)
  (96,96)-(128,128) 피부 단색
"""
from PIL import Image, ImageDraw

SKIN = (255, 226, 209)
SKIN_S = (236, 196, 180)
HAIR = (201, 176, 238)
HAIR_S = (162, 136, 205)
HAIR_H = (226, 211, 250)
EYE = (124, 74, 200)
EYE_D = (70, 38, 124)
EYE_H = (255, 255, 255)
WHITE = (250, 248, 255)
COAT = (246, 244, 253)
COAT_S = (214, 208, 236)
NAVY = (43, 53, 96)
NAVY_S = (30, 37, 70)
GOLD = (255, 212, 71)
GOLD_S = (219, 168, 40)
MOUTH = (168, 84, 96)
BLUSH = (255, 160, 168)
BOOT = (62, 60, 92)
STOCK = (208, 200, 232)

img = Image.new("RGBA", (128, 128), (0, 0, 0, 0))
d = ImageDraw.Draw(img)


def rect(x0, y0, x1, y1, c):
    d.rectangle([x0, y0, x1 - 1, y1 - 1], fill=c)


# ---------------------------------------------------------------- 얼굴 정면
rect(0, 0, 64, 64, SKIN)
# 턱 쪽 살짝 음영
rect(0, 58, 64, 64, SKIN_S)

# 앞머리 — 뾰족한 결 3개 (윗면부터 내려옴)
rect(0, 0, 64, 16, HAIR)
for x0, depth in ((0, 8), (10, 14), (22, 6), (34, 13), (46, 8), (56, 12)):
    rect(x0, 16, min(x0 + 10, 64), 16 + depth, HAIR)
# 앞머리 하이라이트 띠
rect(2, 4, 62, 7, HAIR_H)
# 앞머리 밑 그림자
rect(0, 16, 64, 19, SKIN_S)

# 눈 (좌/우) — 큰 보라 눈
for ex in (9, 39):
    rect(ex, 30, ex + 16, 46, EYE_H)          # 흰자
    rect(ex + 3, 32, ex + 13, 45, EYE)        # 홍채
    rect(ex + 3, 41, ex + 13, 45, EYE_D)      # 아래 짙은 부분
    rect(ex + 5, 34, ex + 9, 38, EYE_H)       # 하이라이트
    rect(ex, 27, ex + 16, 31, EYE_D)          # 위 속눈썹
    rect(ex - 1, 28, ex + 1, 32, EYE_D)       # 눈꼬리
    rect(ex + 15, 28, ex + 17, 32, EYE_D)

# 눈썹
rect(10, 22, 24, 24, HAIR_S)
rect(40, 22, 54, 24, HAIR_S)

# 입 (작은 미소)
rect(29, 52, 35, 54, MOUTH)
rect(31, 54, 33, 55, MOUTH)

# 홍조
for bx in (2, 50):
    rect(bx, 46, bx + 12, 50, BLUSH)

# ------------------------------------------------------- 머리 측/후면 (라벤더)
rect(64, 0, 128, 64, HAIR)
rect(64, 0, 128, 6, HAIR_H)
rect(64, 46, 128, 64, HAIR_S)
# 결 세로선
for x in range(70, 128, 12):
    rect(x, 8, x + 2, 46, HAIR_S)

# ------------------------------------------------------------ 상체 정면 (가운)
rect(0, 64, 64, 96, COAT)
rect(22, 64, 42, 96, NAVY)          # 이너 (남색)
rect(20, 64, 24, 96, COAT_S)        # 가운 여밈 그림자
rect(40, 64, 44, 96, COAT_S)
rect(26, 70, 38, 76, GOLD)          # 노란 리본
rect(30, 70, 34, 76, GOLD_S)
rect(24, 72, 26, 75, GOLD_S)
rect(38, 72, 40, 75, GOLD_S)
rect(0, 90, 64, 96, COAT_S)         # 밑단 그림자

# -------------------------------------------------------- 상체 측/후면 (가운)
rect(64, 64, 96, 96, COAT)
rect(64, 64, 96, 68, COAT_S)
rect(64, 90, 96, 96, COAT_S)
rect(78, 68, 81, 90, COAT_S)        # 등 이음선

# ------------------------------------------------------------------ 팔/소매
rect(96, 64, 128, 96, COAT)
rect(96, 86, 128, 96, SKIN)         # 손목~손
rect(96, 84, 128, 87, COAT_S)

# ---------------------------------------------------------------- 다리/스타킹
rect(0, 96, 32, 128, STOCK)
rect(0, 96, 32, 100, SKIN)          # 허벅지 살짝
rect(0, 100, 32, 103, SKIN_S)

# ------------------------------------------------------------------- 부츠
rect(32, 96, 64, 128, BOOT)
rect(32, 96, 64, 100, NAVY_S)
rect(32, 120, 64, 128, NAVY_S)

# ---------------------------------------------------------------- 단색 스와치
rect(64, 96, 96, 128, HAIR)
rect(96, 96, 128, 128, SKIN)

img.save("atlas.png")
print("atlas.png written 128x128")
