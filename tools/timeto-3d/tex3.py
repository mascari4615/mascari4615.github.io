"""v2 아틀라스 — 전신 64x64. 화면 58px 캐릭터에 텍셀 밀도 1:1 맞춤.

레퍼런스 실측: 캔버스 90px, 캐릭터 58px, 머리 폭 30px, 눈 4x5px.
따라서 머리 정면 = 24텍셀, 눈 = 4x5텍셀로 *직접* 찍는다.
"""
from PIL import Image, ImageDraw

T = 64
SKIN = (255, 224, 205)
SKIN_S = (233, 189, 172)
HAIR = (186, 158, 240)
HAIR_H = (214, 195, 250)
HAIR_S = (140, 112, 200)
EYE = (72, 46, 66)
EYE_L = (150, 110, 214)
HI = (255, 255, 255)
COAT = (252, 251, 255)
COAT_S = (214, 209, 236)
NAVY = (38, 44, 84)
GOLD = (255, 200, 40)
MOUTH = (176, 100, 112)
BLUSH = (255, 158, 170)
BOOT = (56, 54, 86)
STOCK = (222, 218, 240)

img = Image.new("RGBA", (T, T), (0, 0, 0, 0))
d = ImageDraw.Draw(img)


def r(x0, y0, x1, y1, c):
    if x1 > x0 and y1 > y0:
        d.rectangle([x0, y0, x1 - 1, y1 - 1], fill=c)


# ── 얼굴 정면 (0,0)-(24,24)
r(0, 0, 24, 24, SKIN)
r(0, 20, 24, 24, SKIN_S)          # 턱 그림자
# 앞머리 — 톱니 (텍셀 단위로 직접)
r(0, 0, 24, 7, HAIR)
r(1, 1, 23, 2, HAIR_H)
for x0, dep in ((0, 3), (3, 5), (6, 2), (9, 4), (12, 2), (15, 5), (18, 3), (21, 4)):
    r(x0, 7, x0 + 3, 7 + dep, HAIR)
r(0, 7, 24, 8, HAIR_S)            # 앞머리 밑선

# 눈 4x5 — 이게 전부다
for ex in (4, 16):
    r(ex, 11, ex + 4, 16, EYE)
    r(ex, 14, ex + 4, 16, EYE_L)  # 아래 반사
    r(ex, 11, ex + 4, 12, HI)     # 윗 하이라이트 1px
# 입 2x1
r(11, 19, 13, 20, MOUTH)
# 홍조 3x1
r(1, 17, 4, 18, BLUSH)
r(20, 17, 23, 18, BLUSH)

# ── 머리 측/후 (24,0)-(48,24)
r(24, 0, 48, 24, HAIR)
r(24, 0, 48, 2, HAIR_H)
r(24, 18, 48, 24, HAIR_S)
for x in range(27, 48, 5):
    r(x, 3, x + 1, 18, HAIR_S)

# ── 라벤더 단색 (48,0)-(64,16) / 진한 라벤더 (48,16)-(64,24)
r(48, 0, 64, 16, HAIR)
r(48, 16, 64, 24, HAIR_S)

# ── 상체 정면 (0,24)-(24,48)
r(0, 24, 24, 48, COAT)
r(8, 24, 16, 48, NAVY)            # 이너
r(7, 24, 8, 48, COAT_S)
r(16, 24, 17, 48, COAT_S)
r(9, 27, 15, 30, GOLD)            # 리본
r(11, 27, 13, 30, (222, 168, 30))
r(0, 44, 24, 48, COAT_S)

# ── 상체 측/후 (24,24)-(44,48)
r(24, 24, 44, 48, COAT)
r(24, 24, 44, 26, COAT_S)
r(33, 27, 35, 46, COAT_S)
r(24, 44, 44, 48, COAT_S)

# ── 팔 (44,24)-(56,48)
r(44, 24, 56, 48, COAT)
r(44, 42, 56, 48, SKIN)
r(44, 41, 56, 42, COAT_S)

# ── 다리 (0,48)-(16,64)
r(0, 48, 16, 64, STOCK)
r(0, 48, 16, 51, SKIN)

# ── 부츠 (16,48)-(32,64)
r(16, 48, 32, 64, BOOT)
r(16, 48, 32, 50, (40, 38, 66))

# ── 피부 단색 (32,48)-(48,64) / 가운 단색 (48,48)-(64,64)
r(32, 48, 48, 64, SKIN)
r(48, 48, 64, 64, COAT)

img.save("atlas64.png")
print("atlas64.png written 64x64")
