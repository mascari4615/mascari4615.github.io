/**
 * 표면 — 「그림이 나타날 수 있는 곳」이 지키는 약속. 이 파일이 이 시스템에서 제일 중요하다.
 *
 * 도구는 활발하게 늘고 줄고 바뀐다. 그래서 재생 쪽이 도구를 알면 안 된다 — 아는 순간
 * 도구 하나 지울 때마다 재생기가 깨지고, 결국 아무도 안 건드리는 죽은 기능이 된다.
 *
 * 그래서 약속을 **딱 두 개**로 줄였다:
 *   ① 「내 격자는 몇 칸이고, 화면 어디에 있다」 를 말한다  (`measure`)
 *   ② 「이 칸들을 켜라」 를 받는다                        (`paint`)
 *
 * 이게 전부다. 받은 걸 번호판으로 그리든 색칸으로 그리든 글자로 그리든 기계 부하로 그리든
 * 재생기는 모르고, 알 필요도 없다.
 */

/** 표면이 화면에서 차지하는 자리. 픽셀 단위, 문서 기준. */
export interface Rect {
	x: number;
	y: number;
	width: number;
	height: number;
}

/** 표면이 스스로 신고하는 자기 소개. */
export interface SurfaceShape {
	/** 내가 그릴 수 있는 격자 — 가로 칸 수. */
	cols: number;
	/** 세로 칸 수. */
	rows: number;
	/**
	 * 화면에서 내 자리. 주면 **모자이크**(전체 그림의 내 구역만 그림)로 배치되고,
	 * 안 주면 **거울**(전체 그림을 통째로 내 격자에 줄여 그림)로 배치된다.
	 *
	 * 도구 타일처럼 화면에 흩어져 있는 것은 자리를 줘야 「사이트가 통째 액정」이 된다.
	 * 파비콘처럼 화면 밖에 있는 것은 자리가 없으니 거울이 맞다.
	 */
	rect?: Rect;
}

/** 표면에 건네지는 「지금 이 프레임에서 네가 켤 칸」. */
export interface Paint {
	/** 이 표면의 가로 칸 수 (신고한 값). */
	cols: number;
	/** 세로 칸 수. */
	rows: number;
	/** (x, y) 칸이 켜졌나. 범위 밖이면 꺼짐. */
	at(x: number, y: number): boolean;
	/** 켜진 칸 수 — 「몇 칸 켜졌는지」만 필요한 표면(부하 그리기 등)이 훑지 않아도 되게. */
	lit: number;
}

export interface Surface {
	/** 로그·중복 등록 판별용. 안 주면 등록할 때 자동으로 붙는다. */
	readonly id?: string;

	/**
	 * 지금 내 격자와 자리. **매 프레임 불릴 수 있다** — 그래서 싸게 답해야 한다.
	 * 지금은 그릴 수 없으면(화면에서 사라졌거나 접혔거나) `null` 을 준다.
	 * `null` 을 주면 그 프레임에서 그냥 빠진다 — 무대가 알아서 나머지로 다시 배치한다.
	 */
	measure(): SurfaceShape | null;

	/** 이 프레임에서 켤 칸. */
	paint(paint: Paint): void;

	/** 재생이 끝나거나 표면이 떼어질 때. 원래 모습으로 되돌리는 자리. */
	restore?(): void;
}
