import assert from 'node:assert/strict';
import test from 'node:test';

import { 듣는문, 기본값 } from '../assets/listen-gate.js';
import { 넘길말인가, 안넘긴이유, 말이있던구간인가 } from '../dist/index.js';

/** 소리를 이만큼 계속 들려준다. 바뀐 순간들을 돌려준다. */
const 들려주기 = (문, { 크기, 동안, 부터 = 0, 걸음 = 50 }) => {
  const 일어난것 = [];
  for (let t = 부터; t < 부터 + 동안; t += 걸음) {
    const r = 문.들었다(크기, t);
    if (r !== null) 일어난것.push({ 무엇: r, 때: t });
  }
  return { 일어난것, 끝난때: 부터 + 동안 };
};

const 큰소리 = 기본값.문턱 + 0.03;
const 조용 = 0.005;

test('조용하면 안 열린다', () => {
  const { 일어난것 } = 들려주기(new 듣는문(), { 크기: 조용, 동안: 5000 });
  assert.deepEqual(일어난것, []);
});

test('말소리가 이어지면 열린다', () => {
  const { 일어난것 } = 들려주기(new 듣는문(), { 크기: 큰소리, 동안: 2000 });
  assert.equal(일어난것[0]?.무엇, '열림');
});

test('한 번 튄 잡음으로는 안 열린다 — 키보드 소리마다 열리면 못 쓴다', () => {
  const 문 = new 듣는문();
  문.들었다(큰소리, 0);
  문.들었다(큰소리, 50);
  assert.equal(문.들었다(조용, 100), null);
  assert.equal(문.열림, false);
});

test('말 중간에 숨 쉬어도 안 닫힌다', () => {
  const 문 = new 듣는문();
  들려주기(문, { 크기: 큰소리, 동안: 600 });
  assert.equal(문.열림, true);
  들려주기(문, { 크기: 조용, 동안: 400, 부터: 600 }); // 닫히는데(900ms)보다 짧은 숨
  assert.equal(문.열림, true, '400ms 숨에 끊기면 한 문장도 못 받는다');
});

test('말이 끝나고 조용하면 닫힌다', () => {
  const 문 = new 듣는문();
  들려주기(문, { 크기: 큰소리, 동안: 600 });
  const { 일어난것 } = 들려주기(문, { 크기: 조용, 동안: 2000, 부터: 600 });
  assert.equal(일어난것.at(-1)?.무엇, '닫힘');
});

test('얘가 말하는 동안은 안 열린다 — 제 목소리를 제가 받아쓰면 혼자 떠든다', () => {
  const 문 = new 듣는문();
  문.입(true, 0);
  const { 일어난것 } = 들려주기(문, { 크기: 큰소리, 동안: 3000 });
  assert.deepEqual(일어난것, []);
});

test('얘가 말하기 시작하면 열려 있던 문도 닫는다', () => {
  const 문 = new 듣는문();
  들려주기(문, { 크기: 큰소리, 동안: 600 });
  assert.equal(문.열림, true);
  문.입(true, 600);
  assert.equal(문.들었다(큰소리, 650), '닫힘');
});

test('얘가 말을 마쳐도 꼬리 여운 동안은 안 연다 — 스피커 울림이 남는다', () => {
  const 문 = new 듣는문();
  문.입(true, 0);
  문.입(false, 1000);
  들려주기(문, { 크기: 큰소리, 동안: 500, 부터: 1000 }); // 꼬리여운(600ms) 안
  assert.equal(문.열림, false);
  들려주기(문, { 크기: 큰소리, 동안: 600, 부터: 1700 }); // 여운 지난 뒤
  assert.equal(문.열림, true);
});

test('켜 둔 TV 에 영영 매달리지 않는다 — 너무 길면 그냥 닫는다', () => {
  const 문 = new 듣는문();
  const { 일어난것 } = 들려주기(문, { 크기: 큰소리, 동안: 25000, 걸음: 100 });
  assert.equal(일어난것.filter((x) => x.무엇 === '닫힘').length >= 1, true);
});

test('설정을 바꾸면 그대로 먹는다 — 방마다 시끄러운 정도가 다르다', () => {
  const 문 = new 듣는문({ 문턱: 0.5 });
  들려주기(문, { 크기: 0.2, 동안: 3000 });
  assert.equal(문.열림, false);
});

// ── 받아쓴 글을 넘길까 ────────────────────────────────────────────

test('빈 글과 한 글자는 안 넘긴다', () => {
  for (const 글 of ['', '   ', '아', '음', '.', null]) {
    assert.equal(넘길말인가(글), false, `${글} 은 말이 아니다`);
  }
});

test('같은 글자만 늘어선 건 소리지 말이 아니다', () => {
  assert.equal(넘길말인가('아아아아'), false);
});

test('왜 안 넘겼는지 말할 수 있다 — 조용히 버리면 「왜 대답을 안 하지」가 된다', () => {
  assert.equal(안넘긴이유('오늘 뭐 했어'), null);
  assert.match(안넘긴이유(''), /안 들렸다/);
  assert.match(안넘긴이유('시청해주셔서 감사합니다'), /말로 안 봤다/);
});

test('받아쓰기가 조용한 데 붙이는 헛것은 안 넘긴다', () => {
  for (const 글 of ['시청해주셔서 감사합니다', '감사합니다.', 'Thank you.', '구독과 좋아요']) {
    assert.equal(넘길말인가(글), false, `${글}`);
  }
});

test('진짜 말은 넘긴다', () => {
  for (const 글 of ['오늘 뭐 했어', '이거 좀 봐줘', '고마워 진짜로']) {
    assert.equal(넘길말인가(글), true, `${글}`);
  }
});

// ── 말이 있던 구간인가 (글이 아니라 소리로 막는다) ─────────────────

test('말소리가 거의 없던 구간은 무슨 글이 와도 안 넘긴다 — 조용한 3초에 「안녕하세요」가 나왔다', () => {
  assert.equal(말이있던구간인가(0), false);
  assert.equal(말이있던구간인가(150), false);
  assert.match(안넘긴이유('안녕하세요.', 100), /말소리가 거의 없던/);
});

test('실제로 말한 구간은 통과한다 — 좁게 막지 않으면 불러도 대답을 안 한다', () => {
  assert.equal(말이있던구간인가(1200), true);
  assert.equal(안넘긴이유('오늘 뭐 했어', 1200), null);
});

test('창이 안 알려 주면 막지 않는다 — 버튼으로 누른 건 사람이 말한다고 알려 준 것이다', () => {
  assert.equal(말이있던구간인가(null), true);
  assert.equal(말이있던구간인가(undefined), true);
  assert.equal(안넘긴이유('오늘 뭐 했어'), null);
});
