/**
 * 늘 듣기 — 버튼을 안 눌러도 말을 걸 수 있게.
 *
 * 지금은 마이크를 **눌러야** 듣는다. 조수님이 「모든 소통은 음성이 기본」이라고 했는데,
 * 실제로는 얘만 말하고 사람은 버튼을 누르거나 타이핑한다. 반쪽이다.
 *
 * 곁에 있는 존재는 부르면 돌아본다. 그러려면 **늘 열려 있어야** 한다. 다만 늘 열어 두면
 * 새로 생기는 문제가 셋이고, 이 파일은 그 셋을 가른다:
 *
 * 1. **얘 자기 목소리를 듣는다.** 같은 방에서 스피커로 말하니 제 말을 제가 받아쓴다.
 *    → 얘가 말하는 동안은 무조건 안 듣는다. 말이 끝나고도 **꼬리 여운**만큼 더 닫는다.
 * 2. **잡음이 말이 된다.** 키보드 소리, 의자 삐걱, TV. → 한 번 넘었다고 열지 않고
 *    **얼마 동안 이어져야** 연다.
 * 3. **언제 끝났는지 모른다.** → 조용해진 뒤 **얼마간 더 기다렸다가** 닫는다. 바로 닫으면
 *    말 중간의 숨 쉬는 자리에서 끊긴다.
 *
 * 소리 크기(0~1)만 받는다. 소리를 어떻게 재는지는 창이 알아서 한다 — 여기는 **언제 열고
 * 언제 닫나**만 정하고, 그래서 소리 장치 없이 시험할 수 있다.
 */

export const 기본값 = {
  /** 이 크기를 넘으면 말소리로 본다. */
  문턱: 0.045,
  /** 이만큼 이어져야 연다 (ms) — 한 번 튄 잡음으로 열리지 않게. */
  열리는데: 250,
  /** 조용해진 뒤 이만큼 기다렸다 닫는다 (ms) — 숨 쉬는 자리에서 안 끊기게. */
  닫히는데: 900,
  /** 얘가 말을 마친 뒤 이만큼 더 닫아 둔다 (ms) — 제 목소리 꼬리를 안 듣게. */
  꼬리여운: 600,
  /** 이보다 오래 열려 있으면 그냥 닫는다 (ms) — 켜 놓은 TV 에 영영 매달리지 않게. */
  너무길다: 20000,
};

export class 듣는문 {
  constructor(설정 = {}) {
    this.설정 = { ...기본값, ...설정 };
    this.열림 = false;
    this.넘기시작 = null; // 소리가 문턱을 넘기 시작한 시각
    this.조용해진때 = null; // 열려 있는 동안 조용해진 시각
    this.연때 = null;
    this.얘가말끝낸때 = null;
    this.얘가말하는중 = false;
  }

  /** 얘가 말하기 시작했다 / 끝냈다. */
  입(말하는중, 지금) {
    if (this.얘가말하는중 === true && 말하는중 === false) this.얘가말끝낸때 = 지금;
    this.얘가말하는중 = 말하는중;
  }

  /** 지금 귀가 막혀 있나 (얘가 말하는 중이거나 그 꼬리). */
  막힘(지금) {
    if (this.얘가말하는중) return true;
    if (this.얘가말끝낸때 === null) return false;
    return 지금 - this.얘가말끝낸때 < this.설정.꼬리여운;
  }

  /**
   * 소리 한 번 잰 값을 넣는다. 문이 바뀌었으면 '열림' 또는 '닫힘', 아니면 null.
   */
  들었다(크기, 지금) {
    const s = this.설정;

    if (this.막힘(지금)) {
      this.넘기시작 = null;
      // 얘가 말하기 시작하면 **열려 있던 것도 닫는다** — 안 그러면 제 말을 받아쓴다.
      if (this.열림) return this.닫기();
      return null;
    }

    const 소리남 = 크기 >= s.문턱;

    if (this.열림 === false) {
      if (소리남 === false) { this.넘기시작 = null; return null; }
      if (this.넘기시작 === null) this.넘기시작 = 지금;
      if (지금 - this.넘기시작 < s.열리는데) return null;
      this.열림 = true;
      this.연때 = 지금;
      this.조용해진때 = null;
      this.넘기시작 = null;
      return '열림';
    }

    // 열려 있는 동안
    if (지금 - this.연때 >= s.너무길다) return this.닫기();
    if (소리남) { this.조용해진때 = null; return null; }
    if (this.조용해진때 === null) this.조용해진때 = 지금;
    if (지금 - this.조용해진때 < s.닫히는데) return null;
    return this.닫기();
  }

  닫기() {
    if (this.열림 === false) return null;
    this.열림 = false;
    this.연때 = null;
    this.조용해진때 = null;
    this.넘기시작 = null;
    return '닫힘';
  }
}
