/**
 * 늘 듣기 — 버튼을 안 눌러도 말을 걸 수 있게.
 *
 * 지금은 마이크를 **눌러야** 듣는다. 조수님이 「모든 소통은 음성이 기본」이라고 했는데,
 * 실제로는 얘만 말하고 사람은 버튼을 누르거나 타이핑한다. 반쪽이다.
 *
 * 곁에 있는 존재는 부르면 돌아본다. 그러려면 **늘 열려 있어야** 한다. 다만 늘 열어 두면
 * 새로 생기는 문제가 셋이고, 이 파일은 그 셋을 가른다:
 *
 * 1. **얘 자기 목소리를 듣는다.** 같은 방에서 스피커로 말하니 제 말을 제가 받아쓴다.
 *    → 얘가 말하는 동안은 무조건 안 듣는다. 말이 끝나고도 **꼬리 여운**만큼 더 닫는다.
 * 2. **잡음이 말이 된다.** 키보드 소리, 의자 삐걱, TV. → 한 번 넘었다고 열지 않고
 *    **얼마 동안 이어져야** 연다.
 * 3. **언제 끝났는지 모른다.** → 조용해진 뒤 **얼마간 더 기다렸다가** 닫는다. 바로 닫으면
 *    말 중간의 숨 쉬는 자리에서 끊긴다.
 *
 * 소리 크기(0~1)만 받는다. 소리를 어떻게 재는지는 창이 알아서 한다 — 여기는 **언제 열고
 * 언제 닫나**만 정하고, 그래서 소리 장치 없이 시험할 수 있다.
 *
 * ── 76회차: 말 도중에도 끼어들 수 있게 ──
 *
 * 75회차에 「얘가 말하는 동안은 무조건 안 듣는다」로 막았더니, **말을 끊을 수가 없어졌다.**
 * 뉴로사마 급이면 하던 말 중간에 「아니 잠깐」이 먹혀야 한다. 지금은 얘가 다 떠들 때까지
 * 기다렸다가 말해야 한다 — 곁에 있는 존재가 아니라 재생 중인 영상이다.
 *
 * 그런데 그냥 열면 **얘가 제 목소리에 제가 끊긴다.** 스피커 소리가 마이크로 돌아오니까,
 * 한 마디도 못 끝내고 영영 자기를 끊는다. 레퍼런스가 한결같이 짚는 실패도 이것이다
 * (「threshold 가 낮으면 agent 가 제 말을 자른다」).
 *
 * 그래서 셋을 겹친다:
 * 1. **메아리 바닥을 재서 배운다.** 얘가 말하는 동안 마이크에 들어오는 크기가 곧 메아리다.
 *    그 위로 넉넉히 올려야 사람 목소리다. 방마다 스피커마다 다르니 **정해 두지 않고 잰다.**
 * 2. **더 오래 이어져야 한다.** 잠깐 튄 소리로는 안 끊는다.
 * 3. **메아리가 너무 크면 아예 포기한다.** 소리 지우기가 안 먹는 자리에서 억지로 켜면
 *    자기를 끊는 얘가 된다. 그때는 못 한다고 **말하고** 안 켠다 — 조용히 망가지지 않게.
 */

export const 기본값 = {
  /** 이 크기를 넘으면 말소리로 본다. */
  문턱: 0.045,
  /** 이만큼 이어져야 연다 (ms) — 한 번 튄 잡음으로 열리지 않게. */
  열리는데: 250,
  /** 조용해진 뒤 이만큼 기다렸다 닫는다 (ms) — 숨 쉬는 자리에서 안 끊기게. */
  닫히는데: 900,
  /** 얘가 말을 마친 뒤 이만큼 더 닫아 둔다 (ms) — 제 목소리 꼬리를 안 듣게. */
  꼬리여운: 600,
  /** 이보다 오래 열려 있으면 그냥 닫는다 (ms) — 켜 놓은 TV 에 영영 매달리지 않게. */
  너무길다: 20000,

  /** 말 도중에 끊고 들어오는 걸 받나. */
  끼어들기: true,
  /** 메아리 바닥의 몇 배를 넘어야 사람 목소리로 보나. */
  메아리배수: 1.8,
  /** 끼어들기로 보는 최소 문턱 — 메아리가 거의 없어도 이보다 낮게는 안 내려간다. */
  끼어들바닥: 0.08,
  /** 이만큼 이어져야 끊는다 (ms) — 잠깐 튄 소리로는 안 끊는다. */
  끼어드는데: 400,
  /** 메아리 바닥이 이보다 크면 끼어들기를 포기한다 — 켜면 자기를 끊는다. */
  못하겠다: 0.14,
};

export class 듣는문 {
  constructor(설정 = {}) {
    this.설정 = { ...기본값, ...설정 };
    this.열림 = false;
    this.넘기시작 = null; // 소리가 문턱을 넘기 시작한 시각
    this.조용해진때 = null; // 열려 있는 동안 조용해진 시각
    this.연때 = null;
    this.얘가말끝낸때 = null;
    this.얘가말하는중 = false;
    /** 얘가 말하는 동안 마이크로 돌아오는 소리의 크기 = 메아리 바닥. */
    this.메아리바닥 = 0;
    this.메아리잰수 = 0;
    this.끼어들기시작 = null;
  }

  /** 지금 메아리 바닥으로 보아 끼어들기를 받을 수 있나. */
  get 끼어들문턱() {
    return Math.max(this.설정.끼어들바닥, this.메아리바닥 * this.설정.메아리배수);
  }

  /** 소리 지우기가 안 먹어서 끼어들기를 포기해야 하나. */
  get 끼어들포기() {
    return this.설정.끼어들기 === false || this.메아리바닥 >= this.설정.못하겠다;
  }

  /** 얘가 말하기 시작했다 / 끝냈다. */
  입(말하는중, 지금) {
    if (this.얘가말하는중 === true && 말하는중 === false) this.얘가말끝낸때 = 지금;
    this.얘가말하는중 = 말하는중;
  }

  /** 지금 귀가 막혀 있나 (얘가 말하는 중이거나 그 꼬리). */
  막힘(지금) {
    if (this.얘가말하는중) return true;
    if (this.얘가말끝낸때 === null) return false;
    return 지금 - this.얘가말끝낸때 < this.설정.꼬리여운;
  }

  /**
   * 소리 한 번 잰 값을 넣는다. 문이 바뀌었으면 '열림' 또는 '닫힘', 아니면 null.
   */
  들었다(크기, 지금) {
    const s = this.설정;

    if (this.얘가말하는중) {
      /* 얘가 말하는 동안 들어오는 소리 = 메아리. **재서 배운다** — 방마다 스피커마다
         다르므로 정해 두면 어디선가 반드시 틀린다.

         **가장 큰 값으로 배우면 안 된다.** 처음엔 그렇게 했더니 사람이 끼어든 그 소리까지
         메아리로 배워서, 문턱이 같이 뛰어올라 영영 안 걸렸다(실측: 사람 0.4 를 넣었더니
         바닥이 0.4 가 되고 문턱은 0.72 가 됐다). 메아리는 말하는 내내 **깔려 있고**, 사람
         목소리는 잠깐 **솟는다** — 그래서 천천히 따라가는 평균으로 배운다. 잠깐 솟은 것은
         평균을 거의 못 움직인다. */
      /* **한 번에 얼마나 오를 수 있는지도 막는다.** 평균으로 바꾼 뒤에도, 사람이 끼어든
         0.45 가 800ms 이어지자 바닥이 0.045 → 0.157 로 끌려 올라가 그 뒤로 끼어들기가
         통째로 꺼졌다(창이 실제로 받아 가는 파일로 돌려서 봤다). 그래서 매 번 재는 값을
         **지금 바닥의 1.5 배까지만** 인정한다 — 진짜 시끄러운 방이면 몇 백 ms 안에 거기까지
         차오르고, 잠깐 솟은 사람 목소리는 바닥을 못 옮긴다. */
      const 인정 = this.메아리잰수 === 0 ? 크기 : Math.min(크기, this.메아리바닥 * 1.5);
      this.메아리바닥 = this.메아리잰수 === 0 ? 크기 : this.메아리바닥 * 0.98 + 인정 * 0.02;
      this.메아리잰수 += 1;

      // 말하는 동안은 받아쓰기를 안 켠 채로 둔다. 닫혔다는 건 창이 알아야 한다.
      const 닫혔나 = this.열림 ? this.닫기() : null;

      if (this.끼어들포기) { this.끼어들기시작 = null; return 닫혔나; }
      if (크기 < this.끼어들문턱) { this.끼어들기시작 = null; return 닫혔나; }
      if (this.끼어들기시작 === null) this.끼어들기시작 = 지금;
      if (지금 - this.끼어들기시작 < s.끼어드는데) return 닫혔나;
      // 사람이 말을 끊었다. 여기서 문까지 열지는 않는다 — 창이 입을 닫히고 나면
      // 그 다음 재기부터 평소 규칙으로 열린다.
      this.끼어들기시작 = null;
      return '끼어듦';
    }
    this.끼어들기시작 = null;

    if (this.막힘(지금)) {
      this.넘기시작 = null;
      if (this.열림) return this.닫기();
      return null;
    }

    const 소리남 = 크기 >= s.문턱;

    if (this.열림 === false) {
      if (소리남 === false) { this.넘기시작 = null; return null; }
      if (this.넘기시작 === null) this.넘기시작 = 지금;
      if (지금 - this.넘기시작 < s.열리는데) return null;
      this.열림 = true;
      this.연때 = 지금;
      this.조용해진때 = null;
      this.넘기시작 = null;
      return '열림';
    }

    // 열려 있는 동안
    if (지금 - this.연때 >= s.너무길다) return this.닫기();
    if (소리남) { this.조용해진때 = null; return null; }
    if (this.조용해진때 === null) this.조용해진때 = 지금;
    if (지금 - this.조용해진때 < s.닫히는데) return null;
    return this.닫기();
  }

  닫기() {
    if (this.열림 === false) return null;
    this.열림 = false;
    this.연때 = null;
    this.조용해진때 = null;
    this.넘기시작 = null;
    return '닫힘';
  }
}
