import type { Ingredient } from './budget';
import type { Marks } from './tally';

/**
 * 드물게 켜지는 재료는 **켜졌을 때 이겨야 한다.**
 *
 * 81회차에 기록이 이유를 말하게 만들었더니, 82회차 첫 판에서 바로 답이 나왔다. 600턴 넘게
 * 한 번도 안 실리던 「자기상」(조수님이 얘 자신에 대해 물었을 때 쓰는 재료)은 **죽은 게
 * 아니었다.**
 *
 * ```
 * 자기상  ● 한 번도 안 실림  (지나감 613 · 밀림 3 · 꺼짐 610 · 빔 0)
 *         ↳ 자리가 모자랐다 (무게 7) · 「너 뭐 좋아해? 자기소개 좀 해봐」
 * ```
 *
 * 조건은 켜졌고 할 말도 있었다. **하필 그 순간에 예산에서 밀렸다.** 610번은 조건이 안 켜진
 * 게 맞고(물어본 적이 없으니까), 켜진 세 번은 전부 밀렸다.
 *
 * 이게 예산 방식의 구멍이다. **늘 켜져 있는 재료**(기분·들은것·사이)는 매 turn 자리를
 * 다투지만, **드물게 켜지는 재료**는 일 년에 몇 번 오는 자기 차례에 같은 무게로 겨룬다.
 * 그런데 드물게 켜진다는 건 대개 **그 순간에 딱 맞는다**는 뜻이다 — 조수님이 자기소개를
 * 시켰는데 「자기상」이 밀리고 그 자리에 늘 있던 「기분」이 들어가는 건 뒤집힌 것이다.
 *
 * 그래서 **꺼져 있던 비율만큼 켜졌을 때 세진다.** 얼마나 드문지는 우리가 정하지 않는다 —
 * 발동 기록이 이미 세고 있다(오늘만 표를 손으로 늘리다 세 번 당했다). 조수님이 자기 얘기를
 * 자주 묻는 사람이면 저절로 가산이 줄고, 안 묻는 사람이면 커진다.
 *
 * **「빔」은 드묾으로 안 센다.** 빔은 조건이 켜졌는데 만들 게 없었다는 뜻이라 드문 게 아니라
 * 빈 것이다. 그걸 드묾으로 세면 늘 빈 재료가 가장 세진다.
 */

export interface 드묾옵션 {
  /** 이만큼은 지나가 봐야 드문지 아닌지 말할 수 있다. */
  최소본수?: number;
  /** 이 비율보다 자주 켜지면 안 밀어준다. */
  흔한기준?: number;
  /** 가장 드물 때 얹어 줄 무게. */
  상한?: number;
}

const 기본 = { 최소본수: 40, 흔한기준: 0.5, 상한: 12 };

/** 이 재료가 켜졌을 때 얼마나 얹어 줄까. */
export function 드묾가산(m: Marks | undefined, options: 드묾옵션 = {}): number {
  const { 최소본수, 흔한기준, 상한 } = { ...기본, ...options };
  if (m === undefined) return 0;
  const 지나감 = m.실림 + m.밀림 + m.꺼짐 + m.빔;
  // 아직 얼마 안 돌았으면 아무 말도 안 한다 — 새 재료가 첫 turn 에 1등이 되면 안 된다.
  if (지나감 < 최소본수) return 0;
  const 꺼진비율 = m.꺼짐 / 지나감;
  if (꺼진비율 <= 흔한기준) return 0;
  return Math.round((상한 * (꺼진비율 - 흔한기준)) / (1 - 흔한기준));
}

/**
 * 재료 목록에 드묾만큼 얹어 돌려준다. 원본은 안 건드린다.
 *
 * **켜져 있는 것만 얹는다.** 꺼진 재료에 얹어 봐야 어차피 안 실리고, 그 turn 의 계산만
 * 흐려진다.
 */
export function 드묾덧입히기(
  all: readonly Ingredient[],
   보기: (name: string) => Marks | undefined,
  options: 드묾옵션 = {},
): Ingredient[] {
  return all.map((x) => {
    if (x.when === false) return x;
    const 덧 = 드묾가산(보기(x.name), options);
    return 덧 === 0 ? x : { ...x, weight: x.weight + 덧 };
  });
}
