import type { Sensation } from './types';

/**
 * 끊고 들어오는 것 — 맞장구와 진짜 끼어들기를 가른다.
 *
 * 말하는 도중에 사람이 말을 걸면 **즉시 멈춰야** 한다. 그건 이미 된다(끊는 통로를 정해 두고
 * 하던 말을 버린다). 그런데 음성 대화 쪽에서 한결같이 짚는 다음 문제가 있다: **끊고 들어온
 * 게 진짜 끼어들기인지, 그냥 맞장구인지 가려야 한다.**
 *
 * 사람이 「응」 「ㅋㅋ」 하는 건 말을 끊으려는 게 아니라 **듣고 있다는 신호**다. 그걸 끊기로
 * 받으면 얘는 세 마디마다 말이 잘린다. 반대로 「아니 잠깐」을 못 알아들으면 계속 떠든다.
 *
 * 우리 얘는 지금 **통로만 본다** — 창에서 온 것이면 내용과 상관없이 무조건 끊는다. 그래서
 * 「응」 한마디에도 하던 말이 뚝 끊긴다.
 *
 * 재미있게도 우리는 이미 반대쪽을 만들어 뒀다(26회차) — **얘가** 조수님 말 중간에 맞장구를
 * 친다. 그때 지킨 규칙이 그대로 여기에도 맞는다: 맞장구는 말이 아니다.
 */

/** 듣고 있다는 신호 — 말을 끊으려는 게 아니다. */
const 맞장구 = /^[…\s]*(응|어|음|아|오|네|그래|그치|맞아|맞네|ㅇㅇ|ㅋ+|ㅎ+|하하|그렇구나|그러게|알겠어|오케이|ok)[…\s.!?~ㅋㅎ]*$/i;

/** 하던 말을 멈추라는 뜻이 뚜렷한 말. */
const 멈춰 = /(잠깐|잠시|아니|그만|스톱|stop|기다려|멈춰|아냐)/i;

/**
 * 이 말이 **진짜 끼어들기**인가.
 *
 * 맞장구면 아니다. 다만 **맞장구처럼 생겼어도 「아니」가 섞이면** 끼어들기다 —
 * 「아니」는 듣고 있다는 신호가 아니라 뒤집겠다는 신호다.
 */
export function isRealBargeIn(text: string): boolean {
  const t = text.trim();
  if (t === '') return false;
  if (멈춰.test(t)) return true;
  return 맞장구.test(t) === false;
}

/**
 * 끊어도 되는 감각인가 — 통로와 내용을 **둘 다** 본다.
 *
 * 통로만 보면 맞장구에도 말이 잘리고, 내용만 보면 화면 곁눈질이 말을 끊는다.
 */
export function shouldBargeIn(sensation: Sensation, channels: readonly string[]): boolean {
  if (channels.includes(sensation.channel) === false) return false;
  return isRealBargeIn(sensation.text);
}
