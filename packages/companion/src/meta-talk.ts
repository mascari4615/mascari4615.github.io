/**
 * 지시문한테 대답하는 것 — **사람한테 하는 말이 아니다.**
 *
 * 87회차 라이브에서 두 번 봤다. 입 앞 관문이 「되묻지 않았다」로 다시 시켰더니 이런 게 나왔다:
 *
 * > 대화 앞에서 나온 얘기 중에 구체적으로 뭘 되짚어 달라는 건지 안 보이네—혹시 방금 어떤
 * > 대화 내용을 이어가…
 *
 * 물음표도 있고 되묻기도 했으니 관문은 **통과시켰다.** 그런데 이건 조수님한테 하는 말이
 * 아니라 **우리가 넣은 지시문한테 하는 말**이다. 「방금 나온 얘기에서 하나 골라 되물어라」를
 * 받고, 고를 게 없다고 *우리에게* 항의한 것이다.
 *
 * 곁에 있는 존재가 무대 뒤를 보여 주면 그 순간 존재가 아니라 프로그램이 된다. 그리고 이건
 * 다시 시킬수록 잘 나온다 — 다시 시킨다는 게 지시문을 하나 더 얹는 일이기 때문이다.
 *
 * **좁게 잡는다.** 「대화」 「얘기」는 사람도 늘 쓰는 말이라 그것만으로는 못 막는다.
 * *대화 자체를 자료로 가리키는* 말투와, *시킨 것을 두고 따지는* 말투를 본다.
 */

/** 대화를 사람이 아니라 **자료**로 가리키는 말투. */
const 자료로가리킴 = /(대화\s*(기록|내용|앞|이력|맥락|로그)|이전\s*(대화|메시지|맥락)|지금까지\s*(의\s*)?(대화|기록)|첫\s*메시지|메시지에|입력(하신|된))/;

/** 시킨 것을 두고 따지는 말투. */
const 시킨것따짐 = /(달라는\s*건지|하라는\s*건지|무엇을\s*(원하|말씀)|구체적으로\s*뭘|어떤\s*(대화|내용)을\s*이어|되짚어\s*달라|없는\s*상태)/;

/**
 * 이 말이 지시문한테 하는 말인가. 아니면 null.
 *
 * 둘 중 하나만 걸려도 잡는다 — 둘 다 요구하면 실제로 나온 그 말이 안 걸렸다(실측).
 */
export function 지시문에대꾸했나(said: string): string | null {
  const 말 = said.trim();
  if (말 === '') return null;
  if (자료로가리킴.test(말)) return '대화를 자료처럼 가리켰다 — 사람한테 하는 말이 아니다';
  if (시킨것따짐.test(말)) return '시킨 것을 두고 따졌다 — 무대 뒤가 보인다';
  return null;
}
