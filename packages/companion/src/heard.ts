/**
 * 받아쓴 글을 그대로 두뇌에 넘길까.
 *
 * **늘 듣기(75회차)의 진짜 값은 여기서 갈린다.** 버튼을 눌러 말할 때는 사람이 「지금부터
 * 말한다」고 알려 준 것이라 뭐가 들어와도 그 사람 뜻이었다. 귀를 늘 열어 두면 그게 없다 —
 * 문이 열렸다고 들어온 게 다 말은 아니다.
 *
 * 받아쓰기는 **아무 소리에나 그럴듯한 글을 붙인다.** 조용한 구간·잡음 구간에 「음」 「아」
 * 「시청해주셔서 감사합니다」 같은 게 흔히 나온다(자막 데이터로 배운 흔적이다). 이걸 그대로
 * 넘기면 아무도 말 안 걸었는데 얘가 혼자 대꾸한다 — 늘 듣기를 곧바로 못 쓰게 만드는 사고다.
 *
 * **거르는 자리는 서버다.** 창에서 걸러도 소용없다 — 글을 두뇌에 넘기는 건 서버고, 창이
 * 알기 전에 이미 넘어간다. 열쇠가 두 곳에 있으면 조용히 어긋난다(오늘만 세 번 밟았다).
 */

/** 받아쓰기가 조용한 데다 자주 붙이는 말들. */
const 헛것 = [
  '감사합니다', '시청해주셔서감사합니다', '구독과좋아요', '구독좋아요',
  '음', '아', '어', '으', '네', '예',
  'thankyou', 'thanksforwatching', 'you', 'bye', 'okay', 'ok',
];

const 민말 = (글: string): string => 글.replace(/[\s.,!?~…。、·"'’”]/g, '').toLowerCase();

/**
 * 이 받아쓴 글을 사람이 한 말로 볼까.
 *
 * 좁게 막는다 — 진짜 한 말을 막으면 「불러도 대답을 안 한다」가 되고, 그게 헛것보다 나쁘다.
 */
export function 넘길말인가(글: string | null | undefined): boolean {
  const 말 = String(글 ?? '').trim();
  if (말 === '') return false;
  const 민 = 민말(말);
  // 글자 둘 미만은 헛것일 확률이 훨씬 높다. 「응」 「네」 한 마디는 아쉽지만, 아무도
  // 말 안 걸었는데 대꾸하는 쪽이 훨씬 이상하다.
  if (민.length < 2) return false;
  if (헛것.includes(민)) return false;
  // 같은 글자만 늘어선 것(「ㅋㅋㅋ」이 아니라 「아아아아」류)도 소리지 말이 아니다.
  if (/^(.)\1*$/u.test(민)) return false;
  return true;
}


/**
 * 이 듣기 구간이 애초에 **말이 있던 구간**인가.
 *
 * **낱말로 막는 데는 바닥이 있다.** 조용한 3초를 듣게 하고 받아쓴 결과가 「안녕하세요.」였다
 * (실측). 헛것 목록에 없는 멀쩡한 인사말이라 그대로 통과했고, 아무도 말 안 걸었는데 얘가
 * 「뭐, 조수님?」이라고 대꾸했다. 목록에 「안녕하세요」를 더하면 다음엔 다른 게 나온다 —
 * 74회차에 낱말 표로 사건을 줍다가 똑같이 당했다.
 *
 * 그래서 **글이 아니라 소리로 막는다.** 창은 소리 크기를 재서 문을 열고 닫으므로, 그 구간에
 * 말소리가 실제로 얼마나 있었는지 안다. 그 값이 너무 작으면 **무슨 글이 오든 안 넘긴다.**
 * 받아쓰기가 무엇을 지어내든 상관없는 자리다.
 *
 * 창이 안 알려 주면(버튼으로 누른 경우 등) 막지 않는다 — 그때는 사람이 「지금 말한다」고
 * 알려 준 것이라 지어낼 여지가 훨씬 적다.
 */
export function 말이있던구간인가(말한ms: number | null | undefined): boolean {
  if (말한ms === null || 말한ms === undefined || Number.isFinite(말한ms) === false) return true;
  return 말한ms >= 400;
}

/** 왜 안 넘겼는지 — 조용히 버리면 「왜 대답을 안 하지」가 된다. */
export function 안넘긴이유(글: string | null | undefined, 말한ms?: number | null): string | null {
  const 말 = String(글 ?? '').trim();
  if (말 === '') return '아무 말도 안 들렸다';
  if (말이있던구간인가(말한ms) === false) {
    return `말소리가 거의 없던 구간이다 (${Math.round(말한ms as number)}ms) — 받아쓰기가 지어낸 「${말.slice(0, 20)}」`;
  }
  if (넘길말인가(말)) return null;
  return `말로 안 봤다 — 「${말.slice(0, 30)}」`;
}
