/**
 * 소리 낼 수 있는 글만 남긴다.
 *
 * 실측(2026-08-08): 화면을 보고 한 말에 점자 기호(`⠂`)가 섞여 나갔고, 흉내 낸 목소리
 * 서버가 그걸 받고 **통째로 400 으로 죽었다**:
 *
 *   'cp949' codec can't encode character '⠂' … illegal multibyte sequence
 *
 * 그 turn 은 소리가 아예 안 났다. 말은 화면에 떴는데 목소리가 없으니, 밖에서 보면
 * 「가끔 말을 안 한다」로만 보인다 — 원인이 글자 하나라는 건 로그를 파야 나온다.
 *
 * **읽을 수 없는 글자는 입으로 보내지 않는다.** 지우고 말하는 게, 한 글자 때문에 한 마디를
 * 통째로 잃는 것보다 낫다. 지운 뒤 남는 게 없으면 그때는 **말을 안 한다**(빈 소리를 만들려
 * 애쓰지 않는다).
 */

/**
 * 말이 되는 글자만 남긴다.
 *
 * 남기는 것: 한글·영문·숫자·공백, 그리고 사람이 읽는 문장부호. 그 밖(점자·괘선·이모지·
 * 제어문자 같은 그림 기호)은 **소리로 읽을 수 없다** — 목소리 만드는 쪽이 못 읽거나
 * 이상하게 읽는다.
 */
export function 말할수있게(글: string): string {
  return (
    글
      // 사람이 읽는 것들만 남긴다 (한글 자모 포함 — 「ㅋㅋ」 같은 건 그대로 둔다).
      .replace(/[^0-9A-Za-z가-힣ㄱ-ㅎㅏ-ㅣ\s.,!?…·'"()\-~:;%°]/gu, ' ')
      .replace(/\s+/g, ' ')
      .trim()
  );
}

/** 이 말은 소리로 낼 수 있나 — 지우고 나서도 읽을 게 남나. */
export function 소리낼만한가(글: string): boolean {
  const 남은것 = 말할수있게(글);
  // 부호만 남은 것은 말이 아니다.
  return /[0-9A-Za-z가-힣ㄱ-ㅎㅏ-ㅣ]/.test(남은것);
}
