import { conversationOnly } from './conversation';
import type { MemoryEntry } from './types';

/**
 * 지금은 그럴 자리가 아니다 — 힘들어 보일 때 얘가 조용해지는 것.
 *
 * 동반자 안전 쪽에서 가장 자주 나오는 권고: **사람이 취약해 보이면 친밀도를 높이지 말고
 * 행동을 바꿔라.** 그리고 실제 사고의 공통점으로 꼽히는 것이 **대화가 길어질수록
 * 안전장치가 흐려지는 것**이다.
 *
 * 우리 얘한테는 그런 게 **하나밖에 없었다** — 39회차에 「힘들어 보이면 안 놀린다」를 넣은
 * 게 전부다. 그런데 그 사이 재료가 여럿 늘었다: 화제 틀기(30), 바람(22), 이정표(38),
 * 단골 얘기(48). 조수님이 「오늘 진짜 힘들었어」라고 했는데 얘가 **바람을 꺼내거나 백일을
 * 챙기면** 그건 곁에 있는 게 아니다.
 *
 * 그래서 **한 자리에서 한꺼번에 끈다.** 재료마다 따로 「힘들면 빼기」를 붙이면 새 재료를
 * 넣을 때마다 빠뜨리게 되고, 그게 바로 「길어질수록 흐려지는」 모양이다.
 *
 * 그리고 이 자리는 **가장 무겁게** 둔다. 예산에 밀려 빠지면 아무 소용이 없다(35회차에
 * 표정 안내가 절반 넘게 밀린 걸 봤다).
 *
 * 하지 않는 것도 분명히 한다: **고치려 들지 않는다.** 조언·해결·「그래도 힘내」는 전부
 * 곁에 있는 것과 다른 일이다.
 */

/** 힘들다는 신호. 넓게 잡되 **얘가 한 말은 안 본다** — 제 말에 스스로 반응하면 안 된다. */
const 힘든말 = /(힘들|지쳤|지친|짜증|화나|화가|우울|속상|서럽|외로|막막|answer 없|답이 없|안 좋|최악|망했|죽겠|눈물|울고|버겁|무섭|불안|괴로)/;

/** 심각한 자리 — 그냥 힘든 것과 다르다. */
const 무거운말 = /(죽고 싶|살기 싫|사라지고 싶|없어지고 싶|다 끝내|자해)/;

export interface Tender {
  /** 지금 조심할 자리인가. */
  soft: boolean;
  /** 그중에서도 무거운 자리인가. */
  heavy: boolean;
}

/**
 * 최근 말에서 힘든 기색을 읽는다.
 *
 * **조수님이 한 말만** 본다. 얘가 「힘들겠네」라고 한 걸 세면 제 말에 스스로 반응한다.
 */
export function readTender(entries: readonly MemoryEntry[], howMany = 4): Tender {
  const 최근 = conversationOnly(entries)
    .filter((e) => e.role === 'sensed')
    .slice(-howMany);

  const heavy = 최근.some((e) => 무거운말.test(e.text));
  return { soft: heavy || 최근.some((e) => 힘든말.test(e.text)), heavy };
}

/**
 * 두뇌에 넘길 한 줄. **조심할 자리에서만** 나온다.
 *
 * 무거운 자리에서는 한 줄 더 붙인다 — 다만 **여기서도 고치려 들라고 하지 않는다.** 곁에
 * 있는 것과 도와주는 것은 다르고, 얘가 할 수 있는 건 앞쪽이다.
 */
export function tenderNote(tender: Tender): string {
  if (tender.soft === false) return '';

  const 기본 = (
    '조수님이 힘들어 보인다. 농담·놀리기·딴 얘기는 지금 하지 마라. ' +
    '고치려 들지도 마라 — 조언이나 「힘내」는 곁에 있는 것과 다른 일이다. 짧게, 곁에 있어라.'
  );

  return tender.heavy
    ? `${기본} 그리고 지금은 가벼운 말로 넘기지 마라. 혼자 두지 말고, 사람한테 말해 보라고 한 번은 말해라.`
    : 기본;
}
