/**
 * ui-state.ts — **고른 것이 패널을 정한다** (TASK-KL-271 R2 의 규칙, R6 로 꺼냄).
 *
 * 진단서 C2: 화면 상태(무엇을 골랐나·어느 패널을 보나)가 3천 줄짜리 함수 안 지역변수라
 * **「지금 무슨 모드냐」를 검사로 물을 수 없었다.** 그래서 같은 규칙이 여러 자리에 손으로
 * 적혀 있었고(카드 고르기·선 고르기·여럿 고르기·표에서 줄 누르기…), 한 자리를 고치면 다른
 * 자리가 어긋났다.
 *
 * 여기서는 **한 가지 질문**만 순수하게 답한다: 「지금 고른 것이 이러면 어느 패널을 보여야 하나」.
 * 상태를 통째로 옮기는 일(되돌리기·저장까지)은 이 조각의 몫이 아니다 — 규칙부터 꺼내 잠근다.
 */

/** 옆 패널의 갈래 중, **고른 것으로 정해지는** 것들. */
export type SelectionPanel = 'node' | 'edge' | 'many';

export interface Selection {
  /** 고른 카드 수. */
  nodes: number;
  /** 선을 골랐나. */
  edge: boolean;
}

/**
 * ★ 순서가 규칙이다: **여럿 > 선 > 하나/없음**.
 *
 * - 여럿을 고르면 「자리」 패널 — 그때 하고 싶은 일은 낱장 고치기가 아니라 **함께 옮기기·묶기**다.
 * - 선을 고르면 선 패널. 카드와 선을 함께 고르는 길은 없으므로 둘이 다툴 일은 없다.
 * - 하나거나 아무것도 없으면 카드 패널 — 빈 자리에는 「무엇을 만들 건가요」가 들어온다.
 */
export function panelFor(sel: Selection): SelectionPanel {
  if (sel.nodes > 1) return 'many';
  if (sel.edge) return 'edge';
  return 'node';
}

/**
 * 지금 보고 있는 패널을 **고른 것 때문에 바꿔야 하나**.
 *
 * 지금 규칙 = **고른 것이 언제나 이긴다**(거르기·관계망·표를 보다 카드를 짚어도 카드 칸으로 간다).
 * 그 자리에서 바로 고치려는 사람에게는 맞는 손이고, 검사 여럿이 이 손을 딛고 서 있다.
 *
 * ⓘ 「판 전체를 보는 칸은 안 뺏는 게 낫지 않나」를 한 번 시험해 봤는데(2026-08-14), 거르기를
 *   맞추다 카드를 짚는 흐름은 덜 끊기지만 **「카드를 눌렀는데 카드 칸이 안 열린다」**가 되어
 *   더 자주 놀란다(검사 하나가 바로 그 자리에서 걸렸다). 어느 쪽이 나은지는 **쓰는 사람의 취향**이라
 *   여기서 정하지 않는다 — 규칙을 한 곳에 꺼내 두었으니 바꾸고 싶으면 이 함수 하나만 고치면 된다.
 */
export function shouldSwitch(now: string, sel: Selection): boolean {
  return now !== panelFor(sel);
}
