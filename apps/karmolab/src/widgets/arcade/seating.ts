/**
 * 한 방에 몇 명이 앉나. 한 곳에서 정한다 (TASK-KL-264 F1)
 *
 * **혼자 = 봇이 채운 방**이 이 오락실의 전제다. 따로 만든 싱글 모드가 없는 이유가 그것이다.
 * 그런데 자리 수를 게임이 적어 낸 **최솟값**으로 채우고 있었다. `seats: [1, 4]` 인 판 17개는
 * 혼자 열면 봇이 **하나도 안 앉는다**. 스도쿠 경주에 나 혼자 앉아 혼자 푸는 것이 경주로
 * 불리고 있었다. 전제와 코드가 어긋나 있었고, 봇끼리 재 보기 전까지 아무도 몰랐다.
 *
 * 그래서 인원은 **판이 아니라 오락실이** 정한다: 셋. 그 판이 셋을 못 받으면 받는 만큼으로 눌린다.
 *
 * 왜 셋인가. 둘은 나와 상대라 지면 그냥 진 것이고, 넷 이상은 실시간 판에서 화면이 좁다.
 * 셋이면 **등수**가 생긴다(1등, 2등, 3등). 대회가 등수로 셈하는 것과 같은 수라 두 곳이 안 갈린다.
 */
import type { GameDef } from './types';

export const PARTY = 3;

/** 이 판에 앉힐 사람 수. 셋을 그 판이 허용하는 범위로 눌러서. */
export function partySize(g: Pick<GameDef<unknown, unknown>, 'seats'>): number {
  return Math.min(Math.max(g.seats[0], PARTY), g.seats[1]);
}
