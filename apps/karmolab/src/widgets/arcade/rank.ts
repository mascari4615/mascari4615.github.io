/**
 * 등수 — 한 곳에서 센다 (TASK-KL-264 C2)
 *
 * 점수에서 등수를 뽑는 자리가 둘이 되면 **화면과 대회 점수표가 갈린다.** 결과 화면에는 2등이라
 * 적혀 있는데 대회는 2등 점수를 안 주는 판이 나온다. 그래서 여기 하나만 둔다.
 *
 * 올림픽과 같은 셈: **나보다 높은 점수가 몇이나 있나**가 내 등수다. 둘이 1등이면 그 다음은
 * 3등이지 2등이 아니다. 서로 다른 점수를 세는 방식(1등·1등·2등)은 점수를 새게 한다 —
 * 대회에서 실제로 한 판 새어 보고 고쳤다.
 */

/** 0부터. 1등 = 0. */
export function ranks(scores: number[]): number[] {
  return scores.map((s) => scores.filter((x) => x > s).length);
}
