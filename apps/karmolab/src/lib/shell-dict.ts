export function lookupCommand(name: string): CommandDoc | null {
  return COMMANDS[name] || null;
}

/** 옵션 한 줄. 하위 명령이 있으면 그쪽 표를 먼저 본다(`git push -f` 는 `git -f` 가 아니다). */
export function lookupFlag(cmd: string, flag: string, sub = ''): string {
  const doc = COMMANDS[cmd];
  if (!doc) return '';
  if (sub && doc.subFlags?.[sub]?.[flag]) return doc.subFlags[sub][flag];
  return doc.flags?.[flag] || '';
}
