/**
 * audit-generated-registry.mjs — **스스로 「자동 생성」이라 적어 둔 파일**이 파생물 목록에 있나 본다.
 *
 * ★ 왜 (2026-08-17, 하루에 셋): 굽는 파일을 손으로 고치면 다음 빌드에 조용히 지워지고,
 *   안 구우면 낡은 채로 배포된다. 그걸 막는 감사(`audit:generated`)는 있는데 **목록이 손으로 적는 표**라,
 *   새 생성물이 늘 때마다 잊는다. 실제로 셋이 밖에 있었다 — 갈라 굽는 스타일 두 벌 ·
 *   문서 검색 색인 · 공부 지도 강의 표. 그중 스타일은 내가 손으로 고쳤다가 빌드에 지워지는 것을 겪었다.
 *   파일이 첫 줄에 「손으로 고치지 마라」라고 적어 두는데도 그랬다 — 문서는 못 막는다.
 *
 * 그래서 **자기 신고**와 **목록**을 대조한다. 새 생성물이 목록 없이 들어오면 그 자리에서 빨강.
 * 목록에 못 넣을 사정이 있으면 아래 «빼는 것» 에 **왜인지 적고** 넣는다.
 *
 * 사용: node scripts/audit-generated-registry.mjs
 * 나가는 값: 0 통과 · 1 목록에 없는 생성물 있음 · 2 못 봤다(훑을 자리가 없다 — 통과 아님)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { 파생물 } from './lib/generated-artifacts.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const 볼폴더 = ['css', 'data', 'src', 'img'];
const 볼확장자 = new Set(['.css', '.json', '.ts', '.js', '.mjs', '.txt']);

/** 굽는다고 스스로 말하는 표시 — 파일 앞머리에서만 찾는다(본문에 인용된 것과 갈린다). */
const 신고 = /손으로 고치지 마라|자동 생성|AUTO-GENERATED|autogenerated|자동으로 만든/i;

/** 목록에 없어도 되는 자리 — **왜인지 적는다**. */
const 빼는것 = [
  { 규칙: /\.[0-9a-f]{8}\.(css|js)$/, 왜: '해시 붙은 사본 — 정본 파일이 이미 목록에 있고 이건 그 사본이다' },
  { 규칙: /^data\/lessons\/[a-z]{2}\//, 왜: '강의 본문 — 사람이 쓴 글을 담는 자리고, 색인(index.json)만 굽는다' },
  { 규칙: /^css\/fonts\.css$/, 왜: '글꼴 표 — scripts/gen-fonts.py 가 굽는다. 파이썬 + 원본 글꼴 파일이 있어야 해서 감사기가 다시 구울 수 없다(재현 불가라 목록에 넣으면 늘 「낡음」으로 잡힌다)' },
];

let 파일들 = [];
for (const d of 볼폴더) {
  const abs = path.join(root, d);
  if (!fs.existsSync(abs)) continue;
  const 훑기 = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name === 'node_modules' || e.name === 'vendor') continue;
        훑기(full);
      } else if (볼확장자.has(path.extname(e.name))) 파일들.push(full);
    }
  };
  훑기(abs);
}
if (파일들.length === 0) {
  console.error('[생성물 목록] 못 봤다 — 훑을 파일이 0개다 (경로 확인. 통과로 안 센다)');
  process.exit(2);
}

const 적힌것 = new Set(파생물.flatMap((x) => x.outputs).map((p) => p.replace(/\\/g, '/')));
const 빠진것 = [];
for (const full of 파일들) {
  const rel = path.relative(root, full).replace(/\\/g, '/');
  if (적힌것.has(rel)) continue;
  if (빼는것.some((x) => x.규칙.test(rel))) continue;
  /* 폴더째 적어 둔 것도 있다(`img/og`). 그 아래면 적힌 것으로 본다. */
  if ([...적힌것].some((one) => rel.startsWith(`${one}/`))) continue;
  let 머리;
  try {
    머리 = fs.readFileSync(full, 'utf8').slice(0, 400);
  } catch {
    continue;
  }
  if (신고.test(머리)) 빠진것.push(rel);
}

if (빠진것.length) {
  console.error(`[생성물 목록] FAIL — 스스로 「자동 생성」이라 적어 두고 목록에 없는 파일 ${빠진것.length}개:`);
  for (const one of 빠진것.slice(0, 12)) console.error(`  - ${one}`);
  console.error('  목록 = scripts/lib/generated-artifacts.mjs — 굽는 npm 이름·낡으면 무엇이 잘못되나를 같이 적어라.');
  console.error('  목록에 못 넣을 사정이면 이 검사의 «빼는 것» 에 **왜인지 적고** 넣어라.');
  process.exit(1);
}
console.log(`[생성물 목록] 자기 신고와 목록이 맞다 — 적힌 파생물 ${적힌것.size}개 · 훑은 파일 ${파일들.length}개`);
