/**
 * **재우지 말고 멎기를 기다리는** 작은 자 (2026-08-16, TASK-KAR-220)
 *
 * 왜: 검사 249자리가 `waitForTimeout(N)` 뒤에 곧바로 값을 읽는다. 바쁜 판에서는 그 사이에
 * 다시 그리기가 안 끝나 **옛 값**이 읽히고, 그래서 판마다 엉뚱한 검사가 빨개진다
 * (2026-08-16 하루에만 아홉 번 고쳤다 — `memo/rules/quality.md § 순간을 나중에 보지 마라`).
 *
 * 갚기가 더딘 이유는 자리마다 「무엇을 기다려야 하나」를 새로 생각해야 해서다.
 * 그래서 **두 가지 흔한 꼴**을 한 줄로 만든다:
 *   ① `멎을때까지(page, 읽기)` — 값이 두 번 연속 같으면 멎은 것으로 본다(무엇이 될지 모를 때)
 *   ② `될때까지(page, 조건)` — 원하는 상태를 알 때(그쪽이 더 정확하니 가능하면 이걸 써라)
 *
 * 둘 다 **페이지를 안 건드린다** — 재는 자가 재려는 것을 바꾸면 안 된다(같은 날 실측).
 *
 * ★ **아무 데나 갈아 끼우면 안 된다** (2026-08-16, 실제로 깨뜨려 보고 되돌렸다).
 *   `멎을때까지` 는 값이 **어떤 값으로 수렴**할 때만 맞다(거른 결과·그려진 칸 수…).
 *   재우는 까닭이 「그동안 **쌓이라고**」인 자리 — 박자 소리를 몇 번 냈나, 자동 저장이 돌았나 —
 *   에 끼우면 **쌓이기 전에 「멎었다」고 판단**해 버린다(흥 화면에서 세 검사가 그렇게 깨졌다:
 *   `oscillator 42→42`). 그런 자리는 그냥 재우는 게 맞고, `재움-의도` 를 적어 세지 않게 한다.
 *   가르는 물음: **「기다리면 값이 멈추나(→ 이 자), 늘어나나(→ 재우기)」**.
 */

/**
 * 값이 멎을 때까지 기다린다. `읽기` 는 페이지에서 값을 가져오는 함수(비동기 가능).
 * 두 번 연속 같은 값이면 멎은 것으로 보고 그 값을 준다. 끝내 안 멎으면 마지막 값을 준다.
 */
export async function 멎을때까지(page, 읽기, { 간격 = 120, 최대 = 5000 } = {}) {
  let 앞 = await 읽기();
  const 끝 = Date.now() + 최대;
  while (Date.now() < 끝) {
    await page.waitForTimeout(간격);   // 재움-의도: 두 번 재서 견주려면 사이에 틈이 있어야 한다
    const 지금 = await 읽기();
    if (JSON.stringify(지금) === JSON.stringify(앞)) return 지금;
    앞 = 지금;
  }
  return 앞;
}

/**
 * 원하는 상태가 될 때까지 기다린다. 끝내 안 되면 **거짓**을 주고 넘어간다 —
 * 던지지 않는다(그 자리에서 죽으면 무엇이 안 됐는지 못 적는다. 같은 날 세 번 겪었다).
 */
export async function 될때까지(page, 조건, { 최대 = 5000, 인자 } = {}) {
  return page
    .waitForFunction(조건, 인자, { timeout: 최대 })
    .then(() => true)
    .catch(() => false);
}
