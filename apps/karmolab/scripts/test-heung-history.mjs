import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import ts from 'typescript';

const sourcePath=path.resolve('src/widgets/heung/history.ts');
const source=fs.readFileSync(sourcePath,'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};vm.runInNewContext(`(function(exports,module){${compiled}\n})(module.exports,module);`,{module,console,Date,JSON});
const {ProjectHistory}=module.exports;
const normalize=(value)=>({count:Number(value.count)||0});
const history=new ProjectHistory({count:0},normalize,3);
assert.equal(history.record({count:1},'slider',1000),true);
assert.equal(history.record({count:2},'slider',1200),true);
const undo=history.undo({count:2});assert.equal(undo.changed,true);assert.equal(undo.value.count,0,'merged continuous edits undo as one action');
const redo=history.redo({count:0});assert.equal(redo.changed,true);assert.equal(redo.value.count,2,'redo restores merged final value');
history.record({count:3},'',3000);
assert.equal(history.redo({count:3}).changed,false,'new edit clears redo');
history.reset({count:9});
assert.equal(history.undo({count:9}).changed,false,'reset clears history');
console.log('[test-heung-history] ✓ merge · undo · redo · branch clear · reset');
